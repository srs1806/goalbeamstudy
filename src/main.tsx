import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { registerSW } from 'virtual:pwa-register';
import App from './App.tsx';
import { AppErrorBoundary } from './components/AppErrorBoundary.tsx';
import './index.css';

// Capture Chrome/Edge beforeinstallprompt as early as possible before React mounts
window.addEventListener('beforeinstallprompt', (e) => {
  e.preventDefault();
  (window as any).__goalbeamDeferredPrompt = e;
});

// Auto-recover once if a lazy JS chunk URL became stale after a fresh deploy
window.addEventListener('vite:preloadError', (event) => {
  event.preventDefault();
  const retryKey = 'goalbeam_chunk_retry';
  try {
    if (!sessionStorage.getItem(retryKey)) {
      sessionStorage.setItem(retryKey, '1');
      window.location.reload();
    }
  } catch {
    window.location.reload();
  }
});

// Register Workbox Service Worker generated by vite-plugin-pwa for 100% offline capability
registerSW({
  immediate: true,
  onOfflineReady() {
    (window as any).__goalbeamPwaOfflineReady = true;
    window.dispatchEvent(new CustomEvent('goalbeam:pwa-offline-ready'));
  },
  onNeedRefresh() {
    window.dispatchEvent(new CustomEvent('goalbeam:pwa-need-refresh'));
  },
});

(window as any).__goalbeamAppMounted = true;
try {
  sessionStorage.removeItem('goalbeam_boot_retry');
  sessionStorage.removeItem('goalbeam_chunk_retry');
} catch {
  // Ignore sessionStorage errors in restricted iframes
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <AppErrorBoundary>
      <App />
    </AppErrorBoundary>
  </StrictMode>
);
